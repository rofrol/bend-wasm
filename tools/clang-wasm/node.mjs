// A Node host for the modules of tools/clang-wasm/build.sh (TODO
// t-fwjpak4c step D; docs/clang-wasm.md), for the tests only: the shipped
// loader is glue/load-clang.mjs, which has no Node code.
//
//   node node.mjs run FILE.wasm [ARGS...]   runs a program as `./P ARGS`
//   node node.mjs factory FILE.wasm         prints a module (below)
//
// The host imports of patch 0004, module "bend", on this process: write
// copies the bytes to fd 1 or 2 at once (writeSync), exit ends the
// process with the code, now is process.hrtime in nanoseconds.
//
// run instantiates a program, calls __wasm_call_ctors, places argv in
// memory with the module's malloc (argv[0] is "./this.program", as
// Emscripten's) and calls __main_argc_argv; when main returns, the process
// exits with its result, as emcc's runtime does. A trap is thrown, and
// Node exits 1 with it on stderr.
//
// factory prints an ES module whose default export is what an Emscripten
// -sMODULARIZE build exports, as far as the drivers of the library tests
// use it (probe/lib/drive.mjs, tests/negative/consumed.mjs,
// replay/robokill/replay.mjs): an async load() giving each export with a
// "_" prefix, HEAPU8 and HEAPU32. So those drivers run on either build
// unchanged.
import { writeSync } from "node:fs";
import { fileURLToPath, pathToFileURL } from "node:url";
import { readFile } from "node:fs/promises";

// instantiate(file): the started instance's exports, constructors called.
export async function instantiate(file) {
  let mem;
  const bend = {
    write: (fd, data, len) => {
      if (fd !== 1 && fd !== 2) {
        return -1;
      }
      const bytes = new Uint8Array(mem.buffer, data >>> 0, len >>> 0);
      let done = 0;
      while (done < bytes.length) {
        done += writeSync(fd, bytes, done);
      }
      return len;
    },
    exit: (code) => process.exit(code),
    now: () => process.hrtime.bigint(),
  };
  const { instance } = await WebAssembly.instantiate(await readFile(file),
    { bend });
  mem = instance.exports.memory;
  instance.exports.__wasm_call_ctors();
  return instance.exports;
}

// load(url): the Emscripten-shaped module of the library at url.
export async function load(url) {
  const ex = await instantiate(fileURLToPath(url));
  const m = {
    HEAPU8: new Uint8Array(ex.memory.buffer),
    HEAPU32: new Uint32Array(ex.memory.buffer),
  };
  for (const [k, v] of Object.entries(ex)) {
    m[`_${k}`] = v;
  }
  return m;
}

async function run(file, args) {
  const ex = await instantiate(file);
  const enc = new TextEncoder();
  const strs = ["./this.program", ...args].map((a) => {
    const b = enc.encode(a + "\0");
    const p = ex.malloc(b.length) >>> 0;
    new Uint8Array(ex.memory.buffer).set(b, p);
    return p;
  });
  const argv = ex.malloc(4 * (strs.length + 1)) >>> 0;
  new Uint32Array(ex.memory.buffer, argv, strs.length + 1).set([...strs, 0]);
  process.exit(ex.__main_argc_argv(strs.length, argv));
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const [mode, file, ...args] = process.argv.slice(2);
  if (mode === "run" && file !== undefined) {
    await run(file, args);
  } else if (mode === "factory" && file !== undefined && args.length === 0) {
    const wasm = pathToFileURL(file).href;
    console.log(`// Generated by tools/clang-wasm/node.mjs factory: ${file}
// with the Emscripten factory's shape, for the library tests' drivers.
import { load } from ${JSON.stringify(import.meta.url)};
export default () => load(new URL(${JSON.stringify(wasm)}));`);
  } else {
    console.error("usage: node.mjs run FILE.wasm [ARGS...]"
      + " | node.mjs factory FILE.wasm");
    process.exit(2);
  }
}
